-- schema_v70: backup_schema_ddl() - full public schema as runnable SQL
-- Saved as schema.sql in the backup zip (rebuild a new project).
-- Not covered: auth users, storage files. Safe to re-run.
create or replace function public.backup_schema_ddl()
returns text
language sql
stable
security definer
set search_path = public, pg_catalog
as $$
with
hdr as (
  select 0 as ord, ''::text as k,
    '-- jin-dashboard schema ' || now()::text || chr(10) ||
    'set check_function_bodies = false;' as stmt
),
enums as (
  select 10, t.typname::text,
    format('create ' || 'type public.%I as enum (%s);',
      t.typname,
      string_agg(quote_literal(e.enumlabel), ', '
        order by e.enumsortorder))
  from pg_type t
  join pg_namespace n
    on n.oid = t.typnamespace and n.nspname = 'public'
  join pg_enum e on e.enumtypid = t.oid
  group by t.typname
),
seqs as (
  select 20, c.relname::text,
    format('create ' || 'sequence if not exists public.%I;',
      c.relname)
  from pg_class c
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where c.relkind = 'S'
    and not exists (
      select 1 from pg_depend d
      where d.objid = c.oid and d.deptype = 'i')
),
funcs as (
  select 25,
    p.proname::text || '('
      || pg_get_function_identity_arguments(p.oid) || ')',
    pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  join pg_namespace n
    on n.oid = p.pronamespace and n.nspname = 'public'
  where p.prokind in ('f', 'p')
    and not exists (
      select 1 from pg_depend d
      where d.objid = p.oid and d.deptype = 'e')
),
cols as (
  select a.attrelid, a.attnum,
    format('%I %s', a.attname,
      format_type(a.atttypid, a.atttypmod))
    || case
      when a.attgenerated = 's' then
        ' generated always as ('
        || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
      when a.attidentity = 'a' then
        ' generated always as identity'
      when a.attidentity = 'd' then
        ' generated by default as identity'
      when ad.adbin is not null then
        ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
      else '' end
    || case when a.attnotnull then ' not null' else '' end
    as def
  from pg_attribute a
  left join pg_attrdef ad
    on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  where a.attnum > 0 and not a.attisdropped
),
tbls as (
  select 30, c.relname::text,
    format('create ' || 'table if not exists public.%I (%s);',
      c.relname,
      string_agg(cl.def, ', ' order by cl.attnum))
  from pg_class c
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  join cols cl on cl.attrelid = c.oid
  where c.relkind in ('r', 'p')
  group by c.relname
),
cons as (
  select
    case when x.contype = 'f' then 50 else 40 end,
    c.relname::text || '.' || x.conname::text,
    format('alter ' || 'table public.%I add constraint %I %s;',
      c.relname, x.conname, pg_get_constraintdef(x.oid))
  from pg_constraint x
  join pg_class c on c.oid = x.conrelid
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where x.contype in ('p', 'u', 'c', 'x', 'f')
),
idx as (
  select 60, ic.relname::text,
    pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i
  join pg_class ic on ic.oid = i.indexrelid
  join pg_class t on t.oid = i.indrelid
  join pg_namespace n
    on n.oid = t.relnamespace and n.nspname = 'public'
  where not exists (
    select 1 from pg_constraint x
    where x.conindid = i.indexrelid)
),
vws as (
  select 70, c.relname::text,
    format('create ' || 'or replace view public.%I as %s',
      c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where c.relkind = 'v'
),
trg as (
  select 80, c.relname::text || '.' || t.tgname::text,
    pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t
  join pg_class c on c.oid = t.tgrelid
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where not t.tgisinternal
),
rls as (
  select 90, c.relname::text,
    format('alter ' || 'table public.%I enable row level security;',
      c.relname)
    || case when c.relforcerowsecurity then format(
      ' alter ' || 'table public.%I force row level security;',
      c.relname) else '' end
  from pg_class c
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where c.relkind in ('r', 'p') and c.relrowsecurity
),
pol as (
  select 100,
    p.schemaname::text || '.' || p.tablename::text
      || '.' || p.policyname::text,
    format('create ' || 'policy %I on %I.%I as %s for %s to %s',
      p.policyname, p.schemaname, p.tablename,
      lower(p.permissive), lower(p.cmd),
      array_to_string(array(
        select case when r = 'public' then 'public'
          else quote_ident(r) end
        from unnest(p.roles) r), ', '))
    || coalesce(' using (' || p.qual || ')', '')
    || coalesce(' with check (' || p.with_check || ')', '')
    || ';'
  from pg_policies p
  where p.schemaname = 'public'
    or (p.schemaname = 'storage' and p.tablename = 'objects')
),
tacl as (
  select c.oid, r.rolname,
    string_agg(a.privilege_type, ', '
      order by a.privilege_type) as privs
  from pg_class c
  cross join lateral aclexplode(c.relacl) a
  join pg_roles r on r.oid = a.grantee
  where r.rolname in ('anon', 'authenticated', 'service_role')
  group by c.oid, r.rolname
),
tgrant as (
  select 110, c.relname::text,
    format('revoke all on ' || 'table public.%I from '
      || 'anon, authenticated, service_role;', c.relname)
    || coalesce((
      select string_agg(format(' grant %s on ' || 'table public.%I to %I;',
        g.privs, c.relname, g.rolname), '' order by g.rolname)
      from tacl g where g.oid = c.oid), '')
  from pg_class c
  join pg_namespace n
    on n.oid = c.relnamespace and n.nspname = 'public'
  where c.relkind in ('r', 'p', 'v') and c.relacl is not null
),
facl as (
  select p.oid,
    case when a.grantee = 0 then 'public'
      else quote_ident(r.rolname) end as who
  from pg_proc p
  cross join lateral aclexplode(p.proacl) a
  left join pg_roles r on r.oid = a.grantee
  where a.grantee = 0
    or r.rolname in ('anon', 'authenticated', 'service_role')
),
fgrant as (
  select 115,
    p.proname::text || '('
      || pg_get_function_identity_arguments(p.oid) || ')',
    format('revoke all on function public.%I(%s) from '
      || 'public, anon, authenticated, service_role;',
      p.proname, pg_get_function_identity_arguments(p.oid))
    || coalesce((
      select string_agg(format(
        ' grant execute on function public.%I(%s) to %s;',
        p.proname, pg_get_function_identity_arguments(p.oid),
        f.who), '' order by f.who)
      from facl f where f.oid = p.oid), '')
  from pg_proc p
  join pg_namespace n
    on n.oid = p.pronamespace and n.nspname = 'public'
  where p.prokind in ('f', 'p') and p.proacl is not null
    and not exists (
      select 1 from pg_depend d
      where d.objid = p.oid and d.deptype = 'e')
),
pub as (
  select 120, pt.tablename::text,
    format('alter publication supabase_realtime add ' || 'table public.%I;',
      pt.tablename)
  from pg_publication_tables pt
  where pt.pubname = 'supabase_realtime'
    and pt.schemaname = 'public'
),
bkt as (
  select 130, b.id::text,
    format('insert ' || 'into storage.buckets (id, name, public) '
      || 'values (%L, %L, %L) on conflict (id) do nothing;',
      b.id, b.name, b.public)
  from storage.buckets b
),
seqpos as (
  select 140, s.sequencename::text,
    format('select setval(%L, %s, true);',
      'public.' || quote_ident(s.sequencename), s.last_value)
  from pg_sequences s
  where s.schemaname = 'public' and s.last_value is not null
),
allp(ord, k, stmt) as (
  select * from hdr
  union all select * from enums
  union all select * from seqs
  union all select * from funcs
  union all select * from tbls
  union all select * from cons
  union all select * from idx
  union all select * from vws
  union all select * from trg
  union all select * from rls
  union all select * from pol
  union all select * from tgrant
  union all select * from fgrant
  union all select * from pub
  union all select * from bkt
  union all select * from seqpos
)
select string_agg(stmt, chr(10) || chr(10) order by ord, k)
from allp;
$$;

revoke all on function public.backup_schema_ddl()
  from public, anon;
grant execute on function public.backup_schema_ddl()
  to authenticated;

select
  length(d) as chars,
  (select count(*) from regexp_matches(
    d, '^create' || ' table if not', 'gn')) as tables,
  (select count(*) from regexp_matches(
    d, '^create' || ' policy ', 'gn')) as policies
from (select public.backup_schema_ddl() as d) s;
